//! Wayland-native key synthesis via `zwp_virtual_keyboard_v1` (wlr protocols).
//!
//! enigo's Linux backend goes through XTEST over Xwayland, so Key-mode clicks
//! only reach Xwayland windows — native Wayland apps (the common case on KDE
//! Plasma Wayland) never see them. This module injects into the compositor
//! directly: it creates a virtual keyboard on the seat and sends key events
//! with an embedded XKB keymap. Pure-Rust wayland-client (no libwayland).
//!
//! wayland-protocols-wlr does not ship this protocol, so the stable (2018)
//! wlr XML is embedded and the bindings are generated by wayland-scanner.
//!
//! The `key` argument of `zwp_virtual_keyboard_v1.key` is an *evdev* keycode
//! (protocol text: "evdev-style keycode"); KWin/wlroots add +8 internally for
//! xkbcommon. The embedded keymap (`wayland_keymap.xkb`) uses standard XKB
//! numbering (evdev+8) with French accents (é è à ç ù œ €) added on unused
//! slots 120/126/128/129/131/132/136.
//!
//! Init is lazy + sticky (first key send): success or failure is logged once
//! to qac_debug.log (`--debug`). On failure the engine falls back to enigo's
//! XTEST path, which still works for Xwayland windows.

