const KEYMAP: &str = include_str!("wayland_keymap.xkb");

/// evdev keycodes (NOT the +8 XKB numbering) for A..Z, index = letter.
const LETTERS: [u32; 26] = [
    30, 48, 46, 32, 18, 33, 34, 35, 23, 36, 37, 38, 50, 49, 24, 25, 16, 19, 31, 20, 22, 47, 17, 45,
    21, 44,
];

/// Map a stored click-key segment (named key, letter, digit, or punctuation
/// character) to its evdev keycode and whether Shift must be held to produce
/// it on the embedded US-style keymap (uppercase letters, shifted puncts).
fn key_to_code(name: &str) -> Option<(u32, bool)> {
    match name {
        "Escape" | "Esc" => return Some((1, false)),
        "Backspace" => return Some((14, false)),
        "Tab" => return Some((15, false)),
        "Enter" | "Return" => return Some((28, false)),
        "Space" => return Some((57, false)),
        "CapsLock" => return Some((58, false)),
        "Home" => return Some((102, false)),
        "Up" => return Some((103, false)),
        "PageUp" => return Some((104, false)),
        "Left" => return Some((105, false)),
        "Right" => return Some((106, false)),
        "End" => return Some((107, false)),
        "Down" => return Some((108, false)),
        "PageDown" => return Some((109, false)),
        "Insert" => return Some((110, false)),
        "Delete" => return Some((111, false)),
        "F1" => return Some((59, false)),
        "F2" => return Some((60, false)),
        "F3" => return Some((61, false)),
        "F4" => return Some((62, false)),
        "F5" => return Some((63, false)),
        "F6" => return Some((64, false)),
        "F7" => return Some((65, false)),
        "F8" => return Some((66, false)),
        "F9" => return Some((67, false)),
        "F10" => return Some((68, false)),
        "F11" => return Some((87, false)),
        "F12" => return Some((88, false)),
        _ => {}
    }
    let mut chars = name.chars();
    let c = chars.next()?;
    if chars.next().is_some() {
        return None;
    }
    Some(match c {
        'a'..='z' => (LETTERS[(c as u8 - b'a') as usize], false),
        'A'..='Z' => (LETTERS[(c as u8 - b'A') as usize], true),
        '1'..='9' => (c as u32 - '1' as u32 + 2, false),
        '0' => (11, false),
        '-' => (12, false),
        '=' => (13, false),
        '[' => (26, false),
        ']' => (27, false),
        '\\' => (43, false),
        ';' => (39, false),
        '\'' => (40, false),
        '`' => (41, false),
        ',' => (51, false),
        '.' => (52, false),
        '/' => (53, false),
        '!' => (2, true),
        '@' => (3, true),
        '#' => (4, true),
        '$' => (5, true),
        '%' => (6, true),
        '^' => (7, true),
        '&' => (8, true),
        '*' => (9, true),
        '(' => (10, true),
        ')' => (11, true),
        '_' => (12, true),
        '+' => (13, true),
        '{' => (26, true),
        '}' => (27, true),
        '|' => (43, true),
        ':' => (39, true),
        '"' => (40, true),
        '~' => (41, true),
        '<' => (51, true),
        '>' => (52, true),
        '?' => (53, true),
        'é' => (112, false),
        'É' => (112, true),
        'è' => (118, false),
        'È' => (118, true),
        'à' => (120, false),
        'À' => (120, true),
        'ç' => (121, false),
        'Ç' => (121, true),
        'ù' => (123, false),
        'Ù' => (123, true),
        'œ' => (124, false),
        'Œ' => (124, true),
        '€' => (128, false),
        _ => return None,
    })
}

/// Split a stored combo like the engine does: fixed Ctrl -> Shift -> Alt ->
/// Meta press order, main key last. A main key that itself needs Shift (an
/// uppercase letter or shifted punctuation) gets Shift injected into the
/// modifier list. Malformed combos fall back to plain "A" like the engine.
pub fn parse_combo(name: &str) -> (Vec<u32>, u32, bool) {
    let parts: Vec<&str> = name.split('+').collect();
    let Some((main_part, mods_part)) = parts.split_last() else {
        return (vec![42], LETTERS[0], true);
    };
    let mut mods: Vec<u32> = Vec::new();
    let push = |code: u32, mods: &mut Vec<u32>| {
        if !mods.contains(&code) {
            mods.push(code);
        }
    };
    for m in mods_part {
        match *m {
            "Ctrl" => push(29, &mut mods),
            "Shift" => push(42, &mut mods),
            "Alt" => push(56, &mut mods),
            "Meta" => push(125, &mut mods),
            _ => {}
        }
    }
    let (main, need_shift) = match key_to_code(main_part) {
        Some(k) if !matches!(*main_part, "Ctrl" | "Shift" | "Alt" | "Meta") => k,
        _ => (LETTERS[0], true),
    };
    if need_shift {
        push(42, &mut mods);
    }
    // Canonical press order: Ctrl, Shift, Alt, Meta (the main key is not a
    // modifier — key_to_code above rejected those).
    mods.sort_by_key(|c| match c {
        29 => 0,
        42 => 1,
        56 => 2,
        125 => 3,
        _ => 4,
    });
    (mods, main, need_shift)
}

struct Keyboard {
    conn: Connection,
    kb: ZwpVirtualKeyboardV1,
    start: Instant,
}

impl Keyboard {
    fn send(&mut self, mods: &[u32], main: u32) -> Result<(), String> {
        let now = || self.start.elapsed().as_millis() as u32;
        for mc in mods {
            self.kb.key(now(), *mc, 1);
        }
        self.kb.key(now(), main, 1);
        if !mods.is_empty() {
            std::thread::sleep(Duration::from_millis(5));
        }
        self.kb.key(now(), main, 0);
        for mc in mods.iter().rev() {
            self.kb.key(now(), *mc, 0);
        }
        self.conn.flush().map_err(|e| format!("flush: {e}"))
    }
}

/// Sticky lazy init: first send decides success/failure for the process.
static KEYBOARD: OnceLock<Result<Mutex<Keyboard>, String>> = OnceLock::new();

fn keyboard() -> Result<&'static Mutex<Keyboard>, &'static str> {
    match KEYBOARD.get_or_init(init) {
        Ok(m) => Ok(m),
        Err(e) => Err(e.as_str()),
    }
}

fn init() -> Result<Mutex<Keyboard>, String> {
    let result = init_inner();
    match &result {
        Ok(_) => crate::sequence::write_diag("wayland: virtual keyboard ready"),
        Err(e) => {
            crate::sequence::write_diag(&format!("wayland: virtual keyboard unavailable: {e}"))
        }
    }
    result
}

#[derive(Default)]
struct Globals {
    seat: Option<WlSeat>,
    manager: Option<ZwpVirtualKeyboardManagerV1>,
}

impl Dispatch<wl_registry::WlRegistry, ()> for Globals {
    fn event(
        state: &mut Self,
        registry: &wl_registry::WlRegistry,
        event: wl_registry::Event,
        _: &(),
        _: &Connection,
        qh: &QueueHandle<Self>,
    ) {
        if let wl_registry::Event::Global {
            name,
            interface,
            version,
        } = event
        {
            if crate::sequence::debug_enabled() {
                crate::sequence::write_diag(&format!(
                    "wayland: global name={} iface={} ver={}",
                    name, interface, version
                ));
            }
            match interface.as_str() {
                "wl_seat" => {
                    state.seat = Some(registry.bind::<WlSeat, _, _>(name, version, qh, ()));
                }
                "zwp_virtual_keyboard_manager_v1" => {
                    state.manager = Some(registry.bind::<ZwpVirtualKeyboardManagerV1, _, _>(
                        name,
                        version.min(1),
                        qh,
                        (),
                    ));
                }
                _ => {}
            }
        }
    }
}

impl Dispatch<WlSeat, ()> for Globals {
    fn event(
        _: &mut Self,
        _: &WlSeat,
        _: wl_seat::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
    }
}

impl Dispatch<ZwpVirtualKeyboardManagerV1, ()> for Globals {
    fn event(
        _: &mut Self,
        _: &ZwpVirtualKeyboardManagerV1,
        _: <ZwpVirtualKeyboardManagerV1 as wayland_client::Proxy>::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
    }
}

impl Dispatch<ZwpVirtualKeyboardV1, ()> for Globals {
    fn event(
        _: &mut Self,
        _: &ZwpVirtualKeyboardV1,
        _: <ZwpVirtualKeyboardV1 as wayland_client::Proxy>::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
    }
}

fn init_inner() -> Result<Mutex<Keyboard>, String> {
    let conn = Connection::connect_to_env().map_err(|e| format!("connect: {e}"))?;
    let mut queue = conn.new_event_queue();
    let qh = queue.handle();
    let _registry = conn.display().get_registry(&qh, ());
    let mut globals = Globals::default();
    queue
        .roundtrip(&mut globals)
        .map_err(|e| format!("roundtrip: {e}"))?;
    if crate::sequence::debug_enabled() {
        crate::sequence::write_diag(&format!(
            "wayland: globals seat_present={} vkmgr_present={}",
            globals.seat.is_some(),
            globals.manager.is_some()
        ));
    }
    let seat = globals.seat.ok_or("no wl_seat global")?;
    let manager = globals
        .manager
        .ok_or("no zwp_virtual_keyboard_manager_v1 global")?;
    let kb = manager.create_virtual_keyboard(&seat, &qh, ());

    // The protocol takes a readable fd + byte size; a temp file in the session
    // runtime dir is the dependency-free way to hand over the keymap.
    let runtime = std::env::var("XDG_RUNTIME_DIR")
        .unwrap_or_else(|_| format!("/tmp/quietautoclicker-{}", std::process::id()));
    let path = PathBuf::from(&runtime).join(format!(
        "quietautoclicker-keymap-{}.xkb",
        std::process::id()
    ));
    let mut file = fs::OpenOptions::new()
        .create(true)
        .truncate(true)
        .write(true)
        .open(&path)
        .map_err(|e| format!("keymap open: {e}"))?;
    file.write_all(KEYMAP.as_bytes())
        .map_err(|e| format!("keymap write: {e}"))?;
    let read = fs::File::open(&path).map_err(|e| format!("keymap reopen: {e}"))?;
    let _ = fs::remove_file(&path);
    kb.keymap(1, read.as_fd(), KEYMAP.len() as u32);
    conn.flush().map_err(|e| format!("keymap flush: {e}"))?;
    drop(read);

    // Keep the event queue alive with the connection (never dispatched — the
    // virtual keyboard emits no events we care about).
    std::mem::forget(queue);
    Ok(Mutex::new(Keyboard {
        conn,
        kb,
        start: Instant::now(),
    }))
}

/// Send a stored auto-click combo ("J", "Ctrl+Shift+J", "é", ...) through the
/// Wayland virtual keyboard. Err = unavailable/sticky-failed; the engine then
/// falls back to enigo XTEST (Xwayland windows).
pub fn send_combo(name: &str) -> Result<(), String> {
    let m = keyboard()?;
    let mut kbd = m.lock().map_err(|_| "keyboard lock poisoned".to_string())?;
    let (mods, main, _) = parse_combo(name);
    kbd.send(&mods, main)
}

pub fn is_available() -> bool {
    KEYBOARD.get().map(|r| r.is_ok()).unwrap_or(false)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters() {
        assert_eq!(key_to_code("a"), Some((30, false)));
        assert_eq!(key_to_code("J"), Some((36, true)));
        assert_eq!(key_to_code("Z"), Some((44, true)));
    }

    #[test]
    fn digits_and_puncts() {
        assert_eq!(key_to_code("1"), Some((2, false)));
        assert_eq!(key_to_code("0"), Some((11, false)));
        assert_eq!(key_to_code(","), Some((51, false)));
        assert_eq!(key_to_code(";"), Some((39, false)));
        assert_eq!(key_to_code("!"), Some((2, true)));
        assert_eq!(key_to_code("_"), Some((12, true)));
    }

    #[test]
    fn french_extras() {
        assert_eq!(key_to_code("é"), Some((112, false)));
        assert_eq!(key_to_code("ç"), Some((121, false)));
        assert_eq!(key_to_code("€"), Some((128, false)));
        assert_eq!(key_to_code("É"), Some((112, true)));
    }

    #[test]
    fn named_and_function_keys() {
        assert_eq!(key_to_code("Enter"), Some((28, false)));
        assert_eq!(key_to_code("Space"), Some((57, false)));
        assert_eq!(key_to_code("F5"), Some((63, false)));
        assert_eq!(key_to_code("F12"), Some((88, false)));
        assert_eq!(key_to_code("Escape"), Some((1, false)));
    }

    #[test]
    fn combo_order_and_shift_injection() {
        // Plain letter: no mods, uppercase injects Shift.
        assert_eq!(parse_combo("A"), (vec![42], 30, true));
        // Lowercase: no mods, no shift.
        assert_eq!(parse_combo("a"), (vec![], 30, false));
        // Full combo, fixed order even when stored differently.
        assert_eq!(parse_combo("Alt+Ctrl+J"), (vec![29, 42, 56], 36, true));
        // Duplicate modifiers collapse; lowercase main adds no Shift.
        assert_eq!(parse_combo("Ctrl+Ctrl+k"), (vec![29], 37, false));
        // Malformed falls back to "A".
        assert_eq!(parse_combo("Ctrl"), (vec![42], 30, true));
        assert_eq!(parse_combo(""), (vec![42], 30, true));
        // Shifted punct keeps existing Shift (no duplicate).
        assert_eq!(parse_combo("Shift+!"), (vec![42], 2, true));
    }
}
